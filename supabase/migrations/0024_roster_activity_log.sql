-- 排表的操作記錄獨立一張表，不要跟出勤／名單的 activity_log 混在一起。
-- 影片那邊早就是這樣做了（video_activity_log），排表照同一套。
-- 混在一起的問題：出勤一天就有幾十筆，排表存檔的記錄會被沖到翻不到，
-- 而且兩者的保留上限是共用的 —— 出勤記錄多的時候會把排表記錄一起擠掉。
create table if not exists public.roster_activity_log (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  actor_email text,
  actor_role text,
  description text not null
);

-- 讀取一律照 id 由大到小取最近幾筆
create index if not exists roster_activity_log_id_desc_idx
  on public.roster_activity_log (id desc);

-- 跟其他表一樣：開 RLS 但不給任何 policy，只有後端的 service_role 進得來
alter table public.roster_activity_log enable row level security;
