-- 指揮名單：獨立一張表，不是 roster_members 多一個 category。
--
-- 為什麼要獨立：這份名單的全部意義就是「只在排表的指揮下拉出現」。
-- 如果塞進 roster_members，出勤系統、排表的候補／外援／試訓窗格、
-- 可排人數、戰績對名字…每一個讀 roster_members 的地方都要記得再加一條
-- 排除條件，漏掉任何一個指揮就會跑出來。獨立一張表的話，那些地方
-- 根本看不到它，不用靠人記得。
--
-- 只有姓名，沒有職業、身分組、二職 —— 指揮不是被排進格子的人。
create table if not exists public.commander_names (
  id bigint generated by default as identity primary key,
  name text not null,
  sort_order integer not null default 0,
  updated_at timestamptz not null default now()
);

-- 同一個名字只能有一筆。存檔是整份覆寫，重複的名字會讓畫面出現兩列一樣的人。
create unique index if not exists commander_names_name_key
  on public.commander_names (name);

-- 照畫面上的順序讀回來
create index if not exists commander_names_sort_idx
  on public.commander_names (sort_order, id);

-- 跟其他表一樣：開 RLS 但不給任何 policy，只有後端的 service_role 進得來
alter table public.commander_names enable row level security;
